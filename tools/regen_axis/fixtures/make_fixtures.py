def dump(folder: Path, tables: dict[str, list[tuple]]) -> None:
    folder.mkdir(parents=True, exist_ok=True)
    for kind, rows in tables.items():
        with open(folder / NAMES[kind], "w", encoding="utf-8", newline="") as f:
            w = csv.writer(f, lineterminator="\n")
            w.writerow(R.COLUMNS[kind])
            w.writerows(rows)


