def write_csv(path: Path, fields: list[str], rows: list[dict[str, str]]) -> None:
    with path.open("w", encoding="utf-8", newline="") as f:
        w = csv.DictWriter(f, fields)
        w.writeheader()
        w.writerows(rows)


def main() -> None:
    write_csv(HERE / "riyu_hyou.csv", REASON_FIELDS, REASON_ROWS)
    write_csv(HERE / "sai_ichiran.csv", VALUE_FIELDS,
              [dict(zip(VALUE_FIELDS, r)) for r in VALUE_ROWS])
    write_csv(HERE / "hantei.csv", JUDGMENT_FIELDS,
              [dict(zip(JUDGMENT_FIELDS, (str(a), b, c))) for a, b, c in JUDGMENT_ROWS])
