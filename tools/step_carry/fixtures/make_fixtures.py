def w(name: str, head: list[str], rows: list[list[str]]) -> None:
    HERE.mkdir(exist_ok=True)
    with open(HERE / name, "w", encoding="utf-8", newline="") as f:
        cw = csv.writer(f, lineterminator="\n")
        cw.writerow(head)
        cw.writerows(rows)


