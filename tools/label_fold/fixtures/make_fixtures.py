NAMES = ["名前id", "文書id", "名前", "切り方のメモ", "出典"]
STEPS = ["順番", "手順の種類", "除く記号", "出典"]
PAIRS = ["対id", "左の名前id", "右の名前id", "読みのメモ", "出典"]


def put(path: Path, head: list[str], rows: list[list[str]]) -> None:
    path.parent.mkdir(exist_ok=True)
    with path.open("w", encoding="utf-8", newline="") as f:
        w = csv.writer(f, lineterminator="\n")
        w.writerow(head)
        w.writerows(rows)


def case(name: str, names: list, steps: list, pairs: list) -> None:
    for f, h, r in (("names", NAMES, names), ("steps", STEPS, steps), ("pairs", PAIRS, pairs)):
        put(HERE / name / f"{f}.csv", h, r)


